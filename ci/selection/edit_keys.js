(async () => {
  const engine = new URLSearchParams(location.search).get('engine');
  const rows = [];
  const put = (k, v) => rows.push([k, v]);
  const run = (k, f) => { try { put(k, 'ok ' + JSON.stringify(f())); } catch (e) { put(k, e.name + ' ' + e.message); } };
  document.body.innerHTML = '<div id=h contenteditable></div>';
  const sel = getSelection(), h = document.getElementById('h');
  const name = (n) => n === null ? null : n.nodeName + (n.nodeType === 3 ? ':' + n.data.replace(/ /g, '_') : '');
  const st = () => [h.innerHTML, name(sel.anchorNode), sel.anchorOffset];
  const seq = (html, path, off, ops) => { h.innerHTML = html; let n = h; for (const i of path) n = n.childNodes[i]; sel.collapse(n, off);
    for (const op of ops) { if (op === '\n') document.execCommand('insertParagraph'); else if (op === '\b') document.execCommand('delete');
      else if (op === '\x7f') document.execCommand('forwardDelete'); else if (op === '\r') document.execCommand('insertLineBreak'); else document.execCommand('insertText', false, op); }
    return st(); };
  run('space.end', () => seq('ab', [0], 2, [' ']));
  run('space.then', () => seq('ab', [0], 2, [' ', 'c']));
  run('space.two', () => seq('ab', [0], 2, [' ', ' ']));
  run('space.two.then', () => seq('ab', [0], 2, [' ', ' ', 'c']));
  run('space.three.then', () => seq('ab', [0], 2, [' ', ' ', ' ', 'c']));
  run('space.mid', () => seq('ab', [0], 1, [' ']));
  run('space.start', () => seq('ab', [0], 0, [' ']));
  run('space.empty', () => seq('', [], 0, [' ']));
  run('space.before.space', () => seq('a b', [0], 1, [' ']));
  run('space.after.space', () => seq('a b', [0], 2, [' ']));
  run('typed', () => seq('', [], 0, ['h','e','l','l','o',' ','w','o','r','l','d']));
  run('enter.end.p', () => seq('<p>abc</p>', [0, 0], 3, ['\n']));
  run('enter.end.p.type', () => seq('<p>abc</p>', [0, 0], 3, ['\n', 'x']));
  run('enter.start.p', () => seq('<p>abc</p>', [0, 0], 0, ['\n']));
  run('enter.empty', () => seq('', [], 0, ['\n']));
  run('enter.empty.type', () => seq('', [], 0, ['\n', 'x']));
  run('enter.text.end', () => seq('abc', [0], 3, ['\n']));
  run('enter.text.end.type', () => seq('abc', [0], 3, ['\n', 'x']));
  run('enter.div', () => seq('<div>abc</div>', [0, 0], 1, ['\n']));
  run('enter.h1', () => seq('<h1>abc</h1>', [0, 0], 1, ['\n']));
  run('enter.h1.end', () => seq('<h1>abc</h1>', [0, 0], 3, ['\n']));
  run('enter.li', () => seq('<ul><li>abc</li></ul>', [0, 0, 0], 1, ['\n']));
  run('enter.bold', () => seq('<p>a<b>bc</b>d</p>', [0, 1, 0], 1, ['\n']));
  run('enter.twice', () => seq('<p>abc</p>', [0, 0], 3, ['\n', '\n']));
  run('br.end', () => seq('abc', [0], 3, ['\r']));
  run('br.end.type', () => seq('abc', [0], 3, ['\r', 'x']));
  run('br.p.end', () => seq('<p>abc</p>', [0, 0], 3, ['\r']));
  run('bs.text', () => seq('abc', [0], 2, ['\b']));
  run('bs.all', () => seq('ab', [0], 2, ['\b', '\b']));
  run('bs.all.p', () => seq('<p>ab</p>', [0, 0], 2, ['\b', '\b']));
  run('bs.all.p.type', () => seq('<p>ab</p>', [0, 0], 2, ['\b', '\b', 'x']));
  run('bs.empty.p', () => seq('<p>ab</p><p><br></p>', [1], 0, ['\b']));
  run('bs.join.div', () => seq('<div>ab</div><div>cd</div>', [1, 0], 0, ['\b']));
  run('bs.join.text', () => seq('ab<div>cd</div>', [1, 0], 0, ['\b']));
  run('bs.br', () => seq('ab<br>cd', [2], 0, ['\b']));
  run('bs.surrogate', () => seq('a\u{1F600}', [0], 3, ['\b']));
  run('bs.nbsp', () => seq('ab', [0], 2, [' ', '\b']));
  run('bs.word.space', () => seq('a b', [0], 3, ['\b']));
  run('del.fwd', () => seq('abc', [0], 1, ['\x7f']));
  run('type.after.br', () => seq('ab<br>', [], 2, ['x']));
  run('type.before.br.only', () => seq('<br>', [], 0, ['x']));
  run('type.p.br', () => seq('<p><br></p>', [0], 0, ['x']));
  run('cjk', () => seq('', [], 0, ['你', '好', 'a']));
  // events from execCommand
  run('events', () => { h.innerHTML = 'ab'; sel.collapse(h.firstChild, 2); const ev = [];
    for (const t of ['beforeinput', 'input']) h.addEventListener(t, (e) => ev.push([e.type, e.inputType, e.data, e.constructor.name, e.bubbles, e.cancelable, e.isTrusted, e.composed]));
    const r = [document.execCommand('insertText', false, 'X'), document.execCommand('delete'), document.execCommand('insertParagraph')]; return [r, ev]; });
  run('queryCommand', () => ['insertText', 'delete', 'insertParagraph', 'insertLineBreak', 'forwardDelete', 'bold', 'selectAll', 'undo'].map((c) => c + ':' + document.queryCommandSupported(c) + ':' + document.queryCommandEnabled(c)));
  run('exec.noedit', () => { sel.removeAllRanges(); return document.execCommand('insertText', false, 'x'); });
  window.__result = JSON.stringify(rows);
  try { await fetch('/report?engine=' + engine, { method: 'POST', body: JSON.stringify(rows) }); } catch (e) {}
})();
